// MARK: - Estructura que representa un país con sus polígonos geográficos
// (equivalente a un DTO / Value Object en Java)
struct CountryFeature {
    let name: String
    let adminName: String
    let isoCode: String
    let isoA2: String
    let polygons: [CountryPolygon]

    // NUEVO: bounding box del país completo
    let boundingMapRect: MKMapRect
    // Traducir el nombre al español usando el sistema
    var localizedName: String {
        let nameOverrides: [String: String] = ["PS": "Palestina"]
        if isoA2 != "-99" {
            if let override = nameOverrides[isoA2] { return override }
            if let localized = Locale(identifier: "es").localizedString(forRegionCode: isoA2) {
                return localized
            }
        }
        // Fallback manual para territorios sin código ISO
        let manualTranslations: [String: String] = [
            "Somaliland": "Somalilandia",
            "Northern Cyprus": "Chipre del Norte",
            "Kosovo": "Kosovo",
            "Transnistria": "Transnistria",
            "Abkhazia": "Abjasia",
            "South Ossetia": "Osetia del Sur",
        ]
        return manualTranslations[adminName] ?? adminName
    }/// Devuelve el emoji de bandera o nil si no hay código válido
    var flagEmoji: String? {
        guard isoA2.count == 2, isoA2 != "-99" else { return nil }
        return isoA2.uppercased().unicodeScalars.compactMap {
            UnicodeScalar(0x1F1E6 + $0.value - 65)
        }.map { String($0) }.joined()
    }
}

// MARK: - Subclase de MKPolygon con metadatos del país
// Necesitamos subclasificar para poder asociar el nombre/código al overlay del mapa.
// En Java sería una clase que extiende otra añadiendo campos extra.
class CountryPolygon: MKPolygon {
    nonisolated(unsafe) var countryName: String = ""
    nonisolated(unsafe) var isoCode: String = ""
}

// MARK: - Cargador de GeoJSON
// Clase utilitaria estática (como una clase con métodos static en Java)
class GeoJSONLoader {

    /// Carga todos los países desde countries.geojson en el bundle de la app.
    /// - Returns: Array de CountryFeature, o vacío si hay algún error.
    nonisolated static func loadCountries() -> [CountryFeature] {
        // Buscar el archivo en el bundle (como getResourceAsStream en Java)
        guard let url = Bundle.main.url(forResource: "countries", withExtension: "geojson") else {
            return []
        }

        guard let data = try? Data(contentsOf: url) else {
            return []
        }

        guard let json = try? JSONSerialization.jsonObject(with: data) as? [String: Any],
              let features = json["features"] as? [[String: Any]] else {
            return []
        }

        // Mapeamos cada feature GeoJSON a nuestro CountryFeature (como un .stream().map() en Java)
        var result = features.compactMap { parseFeature($0) }
        // El GeoJSON estándar (Natural Earth) no incluye el exclave de Musandam (Omán).
        // Lo añadimos manualmente con un polígono aproximado de la Gobernación de Musandam.
        if let omanIdx = result.firstIndex(where: { $0.isoCode == "OMN" }) {
            if let musandamPoly = makePolygon(rings: [musandamRing], name: "Oman", iso: "OMN") {
                let oman = result[omanIdx]
                let newRect = oman.polygons.map { $0.boundingMapRect }
                    .reduce(musandamPoly.boundingMapRect) { $0.union($1) }
                result[omanIdx] = CountryFeature(
                    name: oman.name, adminName: oman.adminName,
                    isoCode: oman.isoCode, isoA2: oman.isoA2,
                    polygons: oman.polygons + [musandamPoly],
                    boundingMapRect: newRect
                )
            }
        }
        // Reemplazar Mónaco con polígono hardcodeado preciso (Natural Earth es impreciso para microestados)
        if let idx = result.firstIndex(where: { $0.isoCode == "MCO" }),
           let poly = makePolygon(rings: [monacoRing], name: "Monaco", iso: "MCO") {
            let m = result[idx]
            result[idx] = CountryFeature(name: m.name, adminName: m.adminName,
                isoCode: m.isoCode, isoA2: m.isoA2,
                polygons: [poly], boundingMapRect: poly.boundingMapRect)
        }

        // Reemplazar Andorra con polígono hardcodeado preciso
        if let idx = result.firstIndex(where: { $0.isoCode == "AND" }),
           let poly = makePolygon(rings: [andorraRing], name: "Andorra", iso: "AND") {
            let m = result[idx]
            result[idx] = CountryFeature(name: m.name, adminName: m.adminName,
                isoCode: m.isoCode, isoA2: m.isoA2,
                polygons: [poly], boundingMapRect: poly.boundingMapRect)
        }

        // Marruecos con frontera sur recta a 27°40'N (límite con el Sáhara Occidental)
        if let idx = result.firstIndex(where: { $0.isoCode == "MAR" }),
           let poly = makePolygon(rings: [moroccoRing], name: "Morocco", iso: "MAR") {
            let m = result[idx]
            result[idx] = CountryFeature(name: m.name, adminName: m.adminName,
                isoCode: m.isoCode, isoA2: m.isoA2,
                polygons: [poly], boundingMapRect: poly.boundingMapRect)
        }

        // Sáhara Occidental con frontera norte recta a 27°40'N
        if let idx = result.firstIndex(where: { $0.isoCode == "ESH" }),
           let poly = makePolygon(rings: [westernSaharaRing], name: "Western Sahara", iso: "ESH") {
            let m = result[idx]
            result[idx] = CountryFeature(name: m.name, adminName: m.adminName,
                isoCode: m.isoCode, isoA2: m.isoA2,
                polygons: [poly], boundingMapRect: poly.boundingMapRect)
        }

        // Añadir huecos de Vaticano y San Marino a Italia — Natural Earth no incluye
        // interior rings para VAT ni SMR en el polígono continental de ITA.
        if let itaIdx = result.firstIndex(where: { $0.isoCode == "ITA" }) {
            let ita = result[itaIdx]
            // El polígono continental es el de mayor bounding box (más grande que Sicilia/Cerdeña)
            if let mainland = ita.polygons.max(by: {
                $0.boundingMapRect.size.width * $0.boundingMapRect.size.height <
                $1.boundingMapRect.size.width * $1.boundingMapRect.size.height
            }) {
                // Extraer coordenadas del exterior del polígono continental
                var outerCoords = [CLLocationCoordinate2D](repeating: CLLocationCoordinate2D(), count: mainland.pointCount)
                mainland.getCoordinates(&outerCoords, range: NSRange(location: 0, length: mainland.pointCount))

                // Hueco del Vaticano (coordenadas hardcodeadas del GeoJSON exacto)
                let vatCoords: [CLLocationCoordinate2D] = vaticanRing.map {
                    CLLocationCoordinate2D(latitude: $0[1], longitude: $0[0])
                }
                var holes: [MKPolygon] = (mainland.interiorPolygons ?? []) + [
                    MKPolygon(coordinates: vatCoords, count: vatCoords.count)
                ]

                // Hueco de San Marino (extraído del GeoJSON ya cargado)
                if let smr = result.first(where: { $0.isoCode == "SMR" }),
                   let smrPoly = smr.polygons.max(by: {
                       $0.boundingMapRect.size.width * $0.boundingMapRect.size.height <
                       $1.boundingMapRect.size.width * $1.boundingMapRect.size.height
                   }) {
                    var smrCoords = [CLLocationCoordinate2D](repeating: CLLocationCoordinate2D(), count: smrPoly.pointCount)
                    smrPoly.getCoordinates(&smrCoords, range: NSRange(location: 0, length: smrPoly.pointCount))
                    holes.append(MKPolygon(coordinates: smrCoords, count: smrCoords.count))
                }

                let newMainland = CountryPolygon(
                    coordinates: outerCoords,
                    count: outerCoords.count,
                    interiorPolygons: holes
                )
                newMainland.countryName = mainland.countryName
                newMainland.isoCode = mainland.isoCode

                let newPolygons = ita.polygons.map { p -> CountryPolygon in
                    p === mainland ? newMainland : p
                }
                result[itaIdx] = CountryFeature(name: ita.name, adminName: ita.adminName,
                    isoCode: ita.isoCode, isoA2: ita.isoA2,
                    polygons: newPolygons, boundingMapRect: ita.boundingMapRect)
            }
        }

        return result
    }

